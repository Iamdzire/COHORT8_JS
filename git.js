/** Git is a distributed version control system that tracks changes in files over time
  
- Repository: A repository is a storage location for your project files and their version history. It can be local (on your computer) or remote (on a server like GitHub).

- Commit: A commit is a snapshot of your project at a specific point in time. It records the changes made to the files in your repository.

- Branch: A branch is a separate line of development in your repository. It allows you to work on new features or bug fixes without affecting the main codebase.

- Merge: Merging is the process of combining changes from one branch into another. It allows you to integrate new features or bug fixes into the main codebase.

- staging area: The staging area is a place where you can prepare your changes before committing them. You can add files to the staging area using the git add command. */